#!/usr/bin/env python3
"""Build the outbound-domain inputs used by Hugo and the click Function."""

import argparse
import json
import re
from pathlib import Path
from urllib.parse import urlsplit

URL = re.compile(r"https://[^\s<>\"')\]]+")
HOST = re.compile(r"^[a-z0-9](?:[a-z0-9-]{0,61}[a-z0-9])?(?:\.[a-z0-9](?:[a-z0-9-]{0,61}[a-z0-9])?)+$")


def rules(path):
    exact, wildcard, exception = set(), set(), set()
    for raw in path.read_text(encoding="utf-8").splitlines():
        value = raw.strip().lower()
        if not value or value.startswith("//"):
            continue
        if value.startswith("!"):
            exception.add(value[1:])
        elif value.startswith("*."):
            wildcard.add(value[2:])
        else:
            exact.add(value)
    return exact, wildcard, exception


def registrable(host, psl):
    host = host.lower().rstrip(".")
    if len(host) > 253 or not HOST.fullmatch(host):
        return None
    labels = host.split(".")
    exact, wildcard, exception = psl
    suffix_labels = 1
    for index in range(len(labels)):
        candidate = ".".join(labels[index:])
        if candidate in exception:
            suffix_labels = len(labels) - index - 1
            break
        if candidate in exact:
            suffix_labels = max(suffix_labels, len(labels) - index)
        if index and ".".join(labels[index:]) in wildcard:
            suffix_labels = max(suffix_labels, len(labels) - index + 1)
    if len(labels) <= suffix_labels:
        return None
    return ".".join(labels[-suffix_labels - 1 :])


def write_json(path, value):
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(json.dumps(value, indent=2, sort_keys=True) + "\n", encoding="utf-8")


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--root", type=Path, default=Path(__file__).resolve().parent.parent)
    parser.add_argument("--psl", type=Path)
    args = parser.parse_args()
    root = args.root.resolve()
    psl_path = args.psl or root / "analytics/public_suffix_list.dat"
    psl = rules(psl_path)
    exact, wildcard, exception = psl
    hosts = {}
    for path in sorted((root / "content").rglob("*.md")):
        for raw in URL.findall(path.read_text(encoding="utf-8")):
            try:
                host = (urlsplit(raw).hostname or "").lower().rstrip(".")
            except ValueError:
                continue
            domain = registrable(host, psl)
            if domain:
                hosts[host] = domain
    domains = sorted(set(hosts.values()))
    write_json(root / "data/analytics_hosts.json", hosts)
    (root / "static").mkdir(parents=True, exist_ok=True)
    (root / "static/analytics-domains.txt").write_text("\n".join(domains) + "\n", encoding="utf-8")
    module = "// Generated by scripts/build-outbound-domains.py. Domains only.\n"
    module += "export const SITE_DOMAINS = new Set(" + json.dumps(domains, separators=(",", ":")) + ");\n"
    (root / "analytics").mkdir(parents=True, exist_ok=True)
    (root / "analytics/site-domains.mjs").write_text(module, encoding="utf-8")
    rule_module = "// Generated from analytics/public_suffix_list.dat.\n"
    for name, values in (
        ("PSL_EXACT", exact),
        ("PSL_WILDCARD", wildcard),
        ("PSL_EXCEPTION", exception),
    ):
        rule_module += f"export const {name} = new Set(" + json.dumps(sorted(values), separators=(",", ":")) + ");\n"
    (root / "analytics/public-suffix-rules.mjs").write_text(rule_module, encoding="utf-8")


if __name__ == "__main__":
    main()

