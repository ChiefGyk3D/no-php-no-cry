#!/usr/bin/env bash
# Negative test for scripts/check-site-artifact.sh. Builds a good tree in a
# scratch directory under the repository's gitignored tmp/ and one bad variant
# per rule, then asserts the good tree passes and each bad one fails with the
# expected rule name.
set -euo pipefail

root="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
checker="$root/scripts/check-site-artifact.sh"
mkdir -p "$root/tmp"
work="$(mktemp -d "$root/tmp/check-site-artifact.XXXXXX")"
trap 'rm -rf "$work"' EXIT

failures=0
site="$work/site"

make_good() {
    rm -rf "$site"
    mkdir -p "$site/posts/a"
    printf '<!doctype html><title>t</title>\n' >"$site/index.html"
    cp "$root/static/_headers" "$site/_headers"
    cat >"$site/_redirects" <<'RED'
# Generated by Hugo from page aliases. Do not edit. Rules: 3
/2023/02/10/a /posts/a/ 301
/2023/02/10/a/ /posts/a/ 301
/old.html /posts/a/ 302
RED
}

# expect_fail <name> <rule>: the checker must exit 1 and print the rule.
expect_fail() {
    local name="$1" rule="$2" out rc=0
    out="$("$checker" "$site" 2>&1)" || rc=$?
    if [[ $rc -eq 1 && "$out" == *"[$rule]"* ]]; then
        echo "ok: $name"
    else
        echo "FAIL: $name (rc=$rc, wanted rc=1 and [$rule])"
        echo "$out"
        failures=$((failures + 1))
    fi
}

make_good
rc=0
out="$("$checker" "$site" 2>&1)" || rc=$?
if [[ $rc -eq 0 ]]; then
    echo "ok: good tree passes"
else
    echo "FAIL: good tree (rc=$rc)"
    echo "$out"
    failures=$((failures + 1))
fi

make_good
printf 'x\n' >"$site/_worker.js"
expect_fail "_worker.js" reserved-name

make_good
mkdir "$site/_worker.js"
expect_fail "_worker.js directory" reserved-name

make_good
printf 'x\n' >"$site/posts/a/_worker-extra.mjs"
expect_fail "nested _worker* file" reserved-name

make_good
printf '{}\n' >"$site/_routes.json"
expect_fail "_routes.json" reserved-name

make_good
mkdir "$site/functions"
printf 'x\n' >"$site/functions/hook.js"
expect_fail "functions directory" reserved-name

make_good
ln -s index.html "$site/link.html"
expect_fail "symlink" symlink

make_good
rm "$site/_headers"
expect_fail "missing _headers" headers-missing

make_good
printf '\n' >>"$site/_headers"
expect_fail "_headers differs by one byte" headers-differ

# Script files: the CSP allows 'self' scripts for the theme file only, so the
# artifact may hold /theme.js (under 1 KB gzip) and no other script file.
make_good
printf 'document.documentElement.dataset.theme="dark"\n' >"$site/theme.js"
rc=0
"$checker" "$site" >/dev/null 2>&1 || rc=$?
if [[ $rc -eq 0 ]]; then
    echo "ok: a small theme.js passes"
else
    echo "FAIL: a small theme.js was rejected (rc=$rc)"
    failures=$((failures + 1))
fi

make_good
printf 'x\n' >"$site/app.js"
expect_fail "second script file" extra-script

make_good
mkdir -p "$site/js"
printf 'x\n' >"$site/js/theme.js"
expect_fail "theme.js in a subdirectory" extra-script

make_good
printf 'x\n' >"$site/lib.MJS"
expect_fail "uppercase .mjs" extra-script

make_good
head -c 4096 /dev/urandom | od -An -tx1 | tr -d ' \n' >"$site/theme.js"
expect_fail "theme.js over 1 KB gzip" js-budget

make_good
for _ in $(seq 1 1024); do printf 'var a=1;'; done >"$site/theme.js"
rc=0
"$checker" "$site" >/dev/null 2>&1 || rc=$?
if [[ $rc -eq 0 ]]; then
    echo "ok: a large but compressible theme.js under 1 KB gzip passes"
else
    echo "FAIL: compressible theme.js under 1 KB gzip was rejected (rc=$rc)"
    failures=$((failures + 1))
fi

# 'self' authorizes any same-origin response, so the build may hold only files
# of known non-script types (plus /theme.js): a file with no extension or an
# unlisted one is refused whatever it contains, in any directory.
make_good
printf 'x\n' >"$site/payload"
expect_fail "extensionless file" unexpected-file

make_good
printf 'x\n' >"$site/posts/a/payload"
expect_fail "nested extensionless file" unexpected-file

make_good
printf 'x\n' >"$site/data.json"
expect_fail "unlisted extension" unexpected-file

make_good
printf 'x\n' >"$site/.hidden"
expect_fail "dotfile" unexpected-file

make_good
printf 'x\n' >"$site/theme.js.map"
expect_fail "unlisted double extension" unexpected-file

make_good
printf 'x\n' >"$site/page.html.php"
expect_fail "known extension followed by another" unexpected-file

make_good
printf 'x\n' >"$site/trailing."
expect_fail "trailing dot" unexpected-file

make_good
for f in a.html b.css c.svg d.xml e.txt f.png g.jpg h.jpeg i.gif j.webp k.avif l.ico m.woff n.woff2 O.PNG; do
    printf 'x\n' >"$site/$f"
done
printf '<svg xmlns="http://www.w3.org/2000/svg"/>\n' >"$site/c.svg"
rc=0
"$checker" "$site" >/dev/null 2>&1 || rc=$?
if [[ $rc -eq 0 ]]; then
    echo "ok: every listed extension passes"
else
    echo "FAIL: a listed extension was rejected (rc=$rc)"
    "$checker" "$site" || true
    failures=$((failures + 1))
fi

# The one script may not be able to load anything else: no dynamic loading,
# no dynamic code, no computed property names, no escape sequences.
theme_with() {
    make_good
    printf '%s\n' "$1" >"$site/theme.js"
}
theme_with 'var s=document.createElement("script");s.src="/payload";document.head.append(s)'
expect_fail "theme.js creates elements" theme-capability
theme_with 'import("/payload")'
expect_fail "theme.js dynamic import" theme-capability
theme_with 'importScripts("/payload")'
expect_fail "theme.js importScripts" theme-capability
theme_with 'fetch("/payload").then(r=>r.text()).then(eval)'
expect_fail "theme.js fetch and eval" theme-capability
theme_with 'new Function("x")()'
expect_fail "theme.js Function constructor" theme-capability
theme_with 'document.write("x")'
expect_fail "theme.js document.write" theme-capability
theme_with 'document.body.innerHTML="x"'
expect_fail "theme.js innerHTML" theme-capability
theme_with 'document.body.insertAdjacentHTML("beforeend","x")'
expect_fail "theme.js insertAdjacentHTML" theme-capability
theme_with 'document["create"+"Element"]("script")'
expect_fail "theme.js computed property" theme-capability
theme_with 'document.createElement("script")'
expect_fail "theme.js creates a script element" theme-capability
theme_with 'document.createElement`script`'
expect_fail "theme.js template literal" theme-capability
theme_with 'new Worker("/payload")'
expect_fail "theme.js worker" theme-capability
theme_with 'location.href="/payload"'
expect_fail "theme.js navigation" theme-capability
theme_with 'x.setAttribute("src","/payload")'
expect_fail "theme.js setAttribute" theme-capability
theme_with 'setTimeout("x",0)'
expect_fail "theme.js string timer" theme-capability
theme_with 'var f=document.cre/**/ateElement'
expect_fail "theme.js comment inside an identifier" theme-capability

# Each structural ban is tested with input that breaks ONLY that rule (every
# name in it is on the allowlist), next to a control that passes without it.
theme_ok() {
    theme_with "$1"
    local rc=0
    "$checker" "$site" >/dev/null 2>&1 || rc=$?
    if [[ $rc -eq 0 ]]; then
        echo "ok: $2 passes"
    else
        echo "FAIL: $2 was rejected (rc=$rc)"
        "$checker" "$site" || true
        failures=$((failures + 1))
    fi
}
theme_ok 'var a=1;var u=2' "theme.js control without an escape"
theme_with 'var a\u{62}=1'
expect_fail "theme.js escape sequence only" theme-capability
theme_ok 'var a=1' "theme.js control without a bracket"
theme_with 'var a=[1]'
expect_fail "theme.js bracket only" theme-capability
theme_ok 'var a="x"' "theme.js control without a template literal"
theme_with 'var a=`x`'
expect_fail "theme.js template literal only" theme-capability
theme_with 'var a=1/*x*/'
expect_fail "theme.js block comment only" theme-capability
theme_with 'var a=1//x'
expect_fail "theme.js line comment only" theme-capability

# The class of markup-parsing and element-building APIs is closed by an
# allowlist: only the members a theme toggle needs are accepted, so a member
# nobody listed (new or old) is refused.
theme_with 'document.body.setHTMLUnsafe("<b>x</b>")'
expect_fail "theme.js setHTMLUnsafe" theme-capability
theme_with 'Document.parseHTMLUnsafe("<b>x</b>")'
expect_fail "theme.js parseHTMLUnsafe" theme-capability
theme_with 'document.body.setHTML("x")'
expect_fail "theme.js setHTML" theme-capability
theme_with 'const {setHTMLUnsafe}=document.body'
expect_fail "theme.js destructured member" theme-capability
theme_with 'document.body.attachShadow({mode:"open"})'
expect_fail "theme.js attachShadow" theme-capability
theme_with 'document.body.onclick=function(){}'
expect_fail "theme.js handler property" theme-capability
theme_with 'document.createElement(name)'
expect_fail "theme.js createElement with a variable" theme-capability
theme_with 'document.createElement("img")'
expect_fail "theme.js createElement of another tag" theme-capability
theme_with 'document.body.setAttribute("src","/x")'
expect_fail "theme.js setAttribute of another attribute" theme-capability
theme_with 'var a="é"'
expect_fail "theme.js non-ASCII" theme-capability
theme_ok 'var b=document.createElement("button");b.type="button";b.setAttribute("aria-pressed","false");b.textContent="Theme";b.addEventListener("click",function(){var d=document.documentElement;d.classList.toggle("dark");d.setAttribute("data-theme","dark");try{localStorage.setItem("theme",d.classList.contains("dark")?"dark":"light")}catch(e){}});document.body.appendChild(b)' "theme.js toggle button"

make_good
printf 'try{var t=localStorage.getItem("theme")}catch(e){}\ndocument.documentElement.dataset.theme=t||(matchMedia("(prefers-color-scheme: dark)").matches?"dark":"light")\n' >"$site/theme.js"
rc=0
"$checker" "$site" >/dev/null 2>&1 || rc=$?
if [[ $rc -eq 0 ]]; then
    echo "ok: a plain theme.js passes"
else
    echo "FAIL: a plain theme.js was rejected (rc=$rc)"
    "$checker" "$site" || true
    failures=$((failures + 1))
fi

# Markup that is not a page must not carry script either.
make_good
printf '<svg xmlns="http://www.w3.org/2000/svg"><script>x</script></svg>\n' >"$site/logo.svg"
expect_fail "script element in an svg" script-in-markup

make_good
printf '<svg xmlns="http://www.w3.org/2000/svg" onload="x"/>\n' >"$site/logo.svg"
expect_fail "event handler in an svg" script-in-markup

# nosniff keeps the browser from treating a non-script response as a script.
make_good
grep -v 'X-Content-Type-Options' "$root/static/_headers" >"$work/no-nosniff"
cp "$work/no-nosniff" "$site/_headers"
expect_fail_with_expected() {
    local name="$1" rule="$2" exp="$3" out rc=0
    out="$("$checker" "$site" "$exp" 2>&1)" || rc=$?
    if [[ $rc -eq 1 && "$out" == *"[$rule]"* ]]; then
        echo "ok: $name"
    else
        echo "FAIL: $name (rc=$rc, wanted rc=1 and [$rule])"
        echo "$out"
        failures=$((failures + 1))
    fi
}
expect_fail_with_expected "expected headers without nosniff" headers-nosniff "$work/no-nosniff"
for extra in 'X-Content-Type-Options: sniff' 'x-content-type-options: nosniff' 'X-Content-Type-Options: nosniff, sniff'; do
    grep -v 'X-Content-Type-Options' "$root/static/_headers" >"$work/bad-nosniff"
    printf '  X-Content-Type-Options: nosniff\n  %s\n' "$extra" >>"$work/bad-nosniff"
    cp "$work/bad-nosniff" "$site/_headers"
    expect_fail_with_expected "expected headers with a second or conflicting value ($extra)" headers-nosniff "$work/bad-nosniff"
done
grep -v 'X-Content-Type-Options' "$root/static/_headers" >"$work/bad-nosniff"
printf '  X-Content-Type-Options: sniff\n' >>"$work/bad-nosniff"
cp "$work/bad-nosniff" "$site/_headers"
expect_fail_with_expected "expected headers with a different value" headers-nosniff "$work/bad-nosniff"

# The pinned _headers must carry script-src 'self' (not 'none') once the theme
# script ships. The repository's own file is checked here, so a revert to
# 'none' in static/_headers is caught even if the build is byte-identical.
make_good
sed -i "s/script-src 'self'/script-src 'none'/" "$site/_headers"
sed "s/script-src 'self'/script-src 'none'/" "$root/static/_headers" >"$work/none-headers"
rc=0
out="$("$checker" "$site" "$work/none-headers" 2>&1)" || rc=$?
if [[ $rc -eq 1 && "$out" == *"[headers-script-src]"* ]]; then
    echo "ok: expected headers with script-src 'none' rejected"
else
    echo "FAIL: expected headers with script-src 'none' (rc=$rc)"
    echo "$out"
    failures=$((failures + 1))
fi

make_good
sed -i "s/script-src 'self'/script-src 'self' https:/" "$site/_headers"
sed "s/script-src 'self'/script-src 'self' https:/" "$root/static/_headers" >"$work/https-headers"
rc=0
out="$("$checker" "$site" "$work/https-headers" 2>&1)" || rc=$?
if [[ $rc -eq 1 && "$out" == *"[headers-script-src]"* ]]; then
    echo "ok: expected headers with a loosened script-src rejected"
else
    echo "FAIL: expected headers with a loosened script-src (rc=$rc)"
    echo "$out"
    failures=$((failures + 1))
fi

make_good
printf '/* https://evil.example/x 301\n' >>"$site/_redirects"
expect_fail "redirect to a scheme and host" redirects-line

make_good
printf '/a //evil.example/x 301\n' >>"$site/_redirects"
expect_fail "redirect to a scheme-relative host" redirects-line

make_good
printf '/a /\\evil.example/x 301\n' >>"$site/_redirects"
expect_fail "backslash host form" redirects-line

make_good
printf '/a /b 200\n' >>"$site/_redirects"
expect_fail "rewrite status 200" redirects-line

make_good
printf '/a /b 301 force\n' >>"$site/_redirects"
expect_fail "extra field" redirects-line

make_good
printf 'a /b 301\n' >>"$site/_redirects"
expect_fail "source without a leading slash" redirects-line

make_good
printf '/a /b 301\r\n' >>"$site/_redirects"
expect_fail "CRLF line" redirects-line

make_good
{
    echo "# many"
    for i in $(seq 1 2000); do echo "/p$i /q 301"; done
} >"$site/_redirects"
expect_fail "2001 lines" redirects-too-long

make_good
for i in $(seq 1 2000); do echo "/p$i /q 301"; done >"$site/_redirects"
rc=0
"$checker" "$site" >/dev/null 2>&1 || rc=$?
if [[ $rc -eq 0 ]]; then
    echo "ok: exactly 2000 lines passes"
else
    echo "FAIL: 2000 lines should pass (rc=$rc)"
    failures=$((failures + 1))
fi

# Usage errors.
rc=0
"$checker" >/dev/null 2>&1 || rc=$?
[[ $rc -eq 2 ]] && echo "ok: usage refused" || {
    echo "FAIL: no arguments gave rc=$rc, wanted 2"
    failures=$((failures + 1))
}

# A real build, when present, must pass too.
if [[ -f "$root/public/index.html" ]]; then
    if "$checker" "$root/public" >/dev/null 2>&1; then
        echo "ok: public/ passes"
    else
        echo "FAIL: public/ fails the artifact check"
        "$checker" "$root/public" || true
        failures=$((failures + 1))
    fi
fi

if [[ $failures -gt 0 ]]; then
    echo "$failures check(s) failed"
    exit 1
fi
echo "all check-site-artifact tests passed"
