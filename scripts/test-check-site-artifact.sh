# routes_bad <name> <json>: the site file equals an expected file that is not the
# strict shape, so only the shape rule can reject it.
routes_bad() {
    make_good
    printf '%s\n' "$2" >"$work/bad-routes.json"
    cp "$work/bad-routes.json" "$site/_routes.json"
    local out rc=0
    out="$(ROUTES_FILE="$work/bad-routes.json" "$checker" "$site" 2>&1)" || rc=$?
    if [[ $rc -eq 1 && "$out" == *"[routes-invalid]"* ]]; then
        echo "ok: routes shape: $1"
    else
        echo "FAIL: routes shape: $1 (rc=$rc, wanted rc=1 and [routes-invalid])"
        echo "$out"
        failures=$((failures + 1))
    fi
}
routes_bad "not JSON" 'not json'
routes_bad "a list" '[]'
routes_bad "version 2" '{"version":2,"include":["/*"],"exclude":[]}'
routes_bad "version true" '{"version":true,"include":["/*"],"exclude":[]}'
routes_bad "missing exclude" '{"version":1,"include":["/*"]}'
routes_bad "extra key" '{"version":1,"include":["/*"],"exclude":[],"x":1}'
routes_bad "empty include" '{"version":1,"include":[],"exclude":["/a/*"]}'
routes_bad "rule without a slash" '{"version":1,"include":["*"],"exclude":[]}'
routes_bad "rule with a space" '{"version":1,"include":["/a b"],"exclude":[]}'
routes_bad "rule with a backslash" '{"version":1,"include":["/a\\\\b"],"exclude":[]}'
routes_bad "rule over 100 characters" "{\"version\":1,\"include\":[\"/$(printf 'a%.0s' {1..100})\"],\"exclude\":[]}"
routes_bad "non-string rule" '{"version":1,"include":["/*"],"exclude":[5]}'
routes_bad "duplicate key" '{"version":1,"include":["/*"],"include":["/x"],"exclude":[]}'
routes_bad "101 rules" "{\"version\":1,\"include\":[\"/*\"],\"exclude\":[$(printf '"/a%s",' {1..100} | sed 's/,$//')]}"

# What the repository's _routes.json decides (Cloudflare: "exclude" wins over
# "include", and a wildcard matches any number of path segments, so fnmatch with
# its * is the same match). HTML routes must run the Function, assets must not.
# The last two cases are the negative proof that the matcher bites: the old
# "/support/*" rule would exclude the support page and must be seen to do so.
routes_runs() {
    python3 -I - "$1" "$2" <<'PY'
import fnmatch, json, sys
d = json.load(open(sys.argv[1]))
p = sys.argv[2]
hit = lambda rules: any(fnmatch.fnmatchcase(p, r) for r in rules)
sys.exit(0 if hit(d["include"]) and not hit(d["exclude"]) else 1)
PY
}
routes_case() { # <routes-file> <path> <runs|skips> <name>
    local rc=0
    routes_runs "$1" "$2" || rc=$?
    if { [[ "$3" == runs && $rc -eq 0 ]]; } || { [[ "$3" == skips && $rc -eq 1 ]]; }; then
        echo "ok: routes: $4"
    else
        echo "FAIL: routes: $4 (path $2 wanted to $3, rc=$rc)"
        failures=$((failures + 1))
    fi
}
for pth in / /support/ /support/index.html /posts/a/ /about/ /404.html; do
    routes_case "$root/static/_routes.json" "$pth" runs "$pth runs the Function"
done
for pth in /support/qr-btc.svg /support/qr-xmr.svg /support/coin-eth.svg /css/main.css /copy.js /brand/logo.png /fonts/a.woff2; do
    routes_case "$root/static/_routes.json" "$pth" skips "$pth skips the Function"
done
printf '{"version":1,"include":["/*"],"exclude":["/support/*"]}\n' >"$work/old-routes.json"
if routes_runs "$work/old-routes.json" /support/; then
    echo "FAIL: guard: the matcher did not see /support/* exclude /support/"
    failures=$((failures + 1))
else
    echo "ok: guard: the matcher sees /support/* exclude /support/"
fi

make_good
mkdir "$site/functions"
printf 'x\n' >"$site/functions/hook.js"
expect_fail "functions directory" reserved-name

make_good
ln -s index.html "$site/link.html"
expect_fail "symlink" symlink

make_good
rm "$site/_headers"
