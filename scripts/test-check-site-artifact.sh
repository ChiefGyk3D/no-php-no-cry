#!/usr/bin/env bash
# Negative test for scripts/check-site-artifact.sh. Builds a good tree in a
# scratch directory under the repository's gitignored tmp/ and one bad variant
# per rule, then asserts the good tree passes and each bad one fails with the
# expected rule name.
set -euo pipefail

root="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
checker="$root/scripts/check-site-artifact.sh"
mkdir -p "$root/tmp"
work="$(mktemp -d "$root/tmp/check-site-artifact.XXXXXX")"
trap 'rm -rf "$work"' EXIT

failures=0
site="$work/site"

make_good() {
    rm -rf "$site"
    mkdir -p "$site/posts/a"
    printf '<!doctype html><title>t</title>\n' >"$site/index.html"
    cp "$root/static/_headers" "$site/_headers"
    cat >"$site/_redirects" <<'RED'
# Generated by Hugo from page aliases. Do not edit. Rules: 3
/2023/02/10/a /posts/a/ 301
/2023/02/10/a/ /posts/a/ 301
/old.html /posts/a/ 302
RED
}

# expect_fail <name> <rule>: the checker must exit 1 and print the rule.
expect_fail() {
    local name="$1" rule="$2" out rc=0
    out="$("$checker" "$site" 2>&1)" || rc=$?
    if [[ $rc -eq 1 && "$out" == *"[$rule]"* ]]; then
        echo "ok: $name"
    else
        echo "FAIL: $name (rc=$rc, wanted rc=1 and [$rule])"
        echo "$out"
        failures=$((failures + 1))
    fi
}

make_good
rc=0
out="$("$checker" "$site" 2>&1)" || rc=$?
if [[ $rc -eq 0 ]]; then
    echo "ok: good tree passes"
else
    echo "FAIL: good tree (rc=$rc)"
    echo "$out"
    failures=$((failures + 1))
fi

make_good
printf 'x\n' >"$site/_worker.js"
expect_fail "_worker.js" reserved-name

make_good
mkdir "$site/_worker.js"
expect_fail "_worker.js directory" reserved-name

make_good
printf 'x\n' >"$site/posts/a/_worker-extra.mjs"
expect_fail "nested _worker* file" reserved-name

make_good
printf '{}\n' >"$site/_routes.json"
expect_fail "_routes.json" reserved-name

make_good
mkdir "$site/functions"
printf 'x\n' >"$site/functions/hook.js"
expect_fail "functions directory" reserved-name

make_good
ln -s index.html "$site/link.html"
expect_fail "symlink" symlink

make_good
rm "$site/_headers"
expect_fail "missing _headers" headers-missing

make_good
printf '\n' >>"$site/_headers"
expect_fail "_headers differs by one byte" headers-differ

make_good
printf '/* https://evil.example/x 301\n' >>"$site/_redirects"
expect_fail "redirect to a scheme and host" redirects-line

make_good
printf '/a //evil.example/x 301\n' >>"$site/_redirects"
expect_fail "redirect to a scheme-relative host" redirects-line

make_good
printf '/a /\\evil.example/x 301\n' >>"$site/_redirects"
expect_fail "backslash host form" redirects-line

make_good
printf '/a /b 200\n' >>"$site/_redirects"
expect_fail "rewrite status 200" redirects-line

make_good
printf '/a /b 301 force\n' >>"$site/_redirects"
expect_fail "extra field" redirects-line

make_good
printf 'a /b 301\n' >>"$site/_redirects"
expect_fail "source without a leading slash" redirects-line

make_good
printf '/a /b 301\r\n' >>"$site/_redirects"
expect_fail "CRLF line" redirects-line

make_good
{
    echo "# many"
    for i in $(seq 1 2000); do echo "/p$i /q 301"; done
} >"$site/_redirects"
expect_fail "2001 lines" redirects-too-long

make_good
for i in $(seq 1 2000); do echo "/p$i /q 301"; done >"$site/_redirects"
rc=0
"$checker" "$site" >/dev/null 2>&1 || rc=$?
if [[ $rc -eq 0 ]]; then
    echo "ok: exactly 2000 lines passes"
else
    echo "FAIL: 2000 lines should pass (rc=$rc)"
    failures=$((failures + 1))
fi

# Usage errors.
rc=0
"$checker" >/dev/null 2>&1 || rc=$?
[[ $rc -eq 2 ]] && echo "ok: usage refused" || {
    echo "FAIL: no arguments gave rc=$rc, wanted 2"
    failures=$((failures + 1))
}

# A real build, when present, must pass too.
if [[ -f "$root/public/index.html" ]]; then
    if "$checker" "$root/public" >/dev/null 2>&1; then
        echo "ok: public/ passes"
    else
        echo "FAIL: public/ fails the artifact check"
        "$checker" "$root/public" || true
        failures=$((failures + 1))
    fi
fi

if [[ $failures -gt 0 ]]; then
    echo "$failures check(s) failed"
    exit 1
fi
echo "all check-site-artifact tests passed"
